    /// <summary>A checkpoint survives the default payload converter, field for field.</summary>
    /// <remarks>
    /// PINNED RATHER THAN REASONED ABOUT, because a data-converter failure on heartbeat details
    /// does not arrive as an error. The conversion cancels the activity with
    /// <c>ActivityCancelReason.HeartbeatRecordFailure</c> and then fails it, so the symptom on
    /// the board is a cancellation -- indistinguishable at a glance from a worker drain, which is
    /// a thing this case does on purpose.
    /// <para>
    /// Six longs and a <c>DateTimeOffset</c> is about 100 bytes against a 2 MB default payload
    /// limit, so size is not the risk. The risks are precision (hence the sub-second ticks on
    /// <see cref="Recorded"/>) and binding, which the next test covers.
    /// </para>
    /// </remarks>
    [Fact]
    public void ACheckpointRoundTripsThroughTheDefaultConverter()
    {
        var converter = DataConverter.Default.PayloadConverter;
        var before = MidScan();

        var after = converter.ToValue<FileScanCheckpoint>(converter.ToPayload(before));

        // Record equality is structural, so this covers all seven fields at once.
        Assert.Equal(before, after);

        // And the round trip must not merely be equal, it must still be RESUMABLE: this is the
        // assertion that would fail if the converter ever started truncating a long or dropping
        // sub-second ticks, both of which leave a checkpoint that looks fine field by field.
        Assert.Null(FileScanActivities.CheckpointDisagreement(after));
        Assert.Equal(Recorded, after.RecordedAtUtc);
    }

    /// <summary>A RENAMED parameter binds nothing, yields default(T), and is caught.</summary>
    /// <remarks>
    /// The schema-drift failure driven through the REAL converter rather than constructed by
    /// hand, which is what makes it evidence rather than a restatement of
    /// <see cref="RejectsAZeroedIndexSumBesideACorrectByteOffset"/>. The payload here carries
    /// <c>IndexSumTotal</c> where the record declares <c>IndexSum</c> -- the single-word rename
    /// a tidy-up produces -- and everything else is spelled correctly.
    /// <para>
    /// MEASURED with this exact payload: <c>Rows</c>, <c>ByteOffset</c>, <c>WordByteSum</c>,
    /// <c>FileRows</c>, <c>FileBytes</c> and <c>RecordedAtUtc</c> all bind correctly and
    /// <c>IndexSum</c> comes back 0, with NO exception from the converter. That is what a silent
    /// wrong answer looks like at the point it is created.
    /// </para>
    /// </remarks>
    [Fact]
    public void ARenamedParameterBindsNothingAndTheDriftCheckCatchesIt()
    {
        var converter = DataConverter.Default.PayloadConverter;

        var drifted = converter.ToValue<FileScanCheckpoint>(converter.ToPayload(new
        {
            Rows = MidRows,
            ByteOffset = MidByteOffset,
            IndexSumTotal = MidIndexSum,   // <- the rename
            WordByteSum = MidWordByteSum,
            FileRows = Rows100Mb,
            FileBytes = Bytes100Mb,
            RecordedAtUtc = Recorded,
        }));

        // EVERY OTHER FIELD ARRIVES CORRECT. Without these, a converter that bound nothing at
        // all would pass the assertion below for entirely the wrong reason, and this test would
        // stop being about a rename.
        Assert.Equal(MidRows, drifted.Rows);
        Assert.Equal(MidByteOffset, drifted.ByteOffset);
        Assert.Equal(MidWordByteSum, drifted.WordByteSum);
        Assert.Equal(Rows100Mb, drifted.FileRows);
        Assert.Equal(Bytes100Mb, drifted.FileBytes);
        Assert.Equal(Recorded, drifted.RecordedAtUtc);

        // The renamed one is default(long), and the converter raised nothing.
        Assert.Equal(0L, drifted.IndexSum);

        // Which is precisely the case CheckpointDisagreement exists to refuse.
        Assert.NotNull(FileScanActivities.CheckpointDisagreement(drifted));
    }

    /// <summary>The RESULT record round-trips too, since it is a replay-visible schema.</summary>
    /// <remarks>
    /// An activity's return value lands in the history and is read back on replay, so its shape
    /// is a contract about NAMES. The hazard specific to <c>FileScanResult</c> is four adjacent
    /// longs, three of which are plausible at the same magnitude for the 100 MB corpus
    /// (99,999,968 bytes against 65,508,200 word bytes), so a positional construction compiles
    /// clean and reports the word-byte sum as the byte count. Named arguments here, and the
    /// round trip pins that the names are what travel.
    /// </remarks>
    [Fact]
    public void AResultRoundTripsThroughTheDefaultConverter()
    {
        var converter = DataConverter.Default.PayloadConverter;
        var before = new FileScanResult(
            Rows: Rows100Mb,
            Bytes: Bytes100Mb,
            IndexSum: IndexSum100Mb,
            WordByteSum: WordByteSum100Mb,
            Verified: true);

        var after = converter.ToValue<FileScanResult>(converter.ToPayload(before));

        Assert.Equal(before, after);
        Assert.True(after.Verified);
    }
